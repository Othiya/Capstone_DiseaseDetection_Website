/** Fish disease name in the chosen language (falls back to the English name). */
export function fishDiseaseName(name: string | undefined, lang: Lang): string {
  if (!name) return '';
  if (lang !== 'bn') return name;
  return FISH_DISEASE_NAMES_BN[normalize(name)] ?? name;
}

